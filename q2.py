def combine_lists(numbers, strings):
    print("\nCombined elements:")
    
    for i in range(5):
        print(numbers[i], strings[i])


# First list containing 5 integers
numbers = [10, 20, 30, 40, 50]

# Second list containing 5 strings
strings = ["Apple", "Banana", "Mango", "Orange", "Grapes"]

# Function call
combine_lists(numbers, strings)
